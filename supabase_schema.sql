-- 1. Création de la table de télémétrie
CREATE TABLE IF NOT EXISTS public.telemetry (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
    voltage NUMERIC(6, 2) NOT NULL,      -- Tension en Volts (ex: 231.40)
    current NUMERIC(6, 3) NOT NULL,      -- Courant en Ampères (ex: 3.420)
    power NUMERIC(8, 2) NOT NULL,        -- Puissance active en Watts (ex: 780.50)
    energy NUMERIC(10, 3) NOT NULL,      -- Énergie cumulée en kWh (ex: 145.230)
    frequency NUMERIC(5, 2) DEFAULT 50.0,-- Fréquence en Hz (ex: 50.00)
    pf NUMERIC(4, 2) DEFAULT 1.0,        -- Facteur de puissance (ex: 0.98)
    wifi_rssi INTEGER,                   -- Puissance signal Wi-Fi en dBm
    alert BOOLEAN DEFAULT FALSE          -- Indicateur de surpuissance / anomalie
);

-- 2. Activation des politiques de sécurité Row Level Security (RLS)
ALTER TABLE public.telemetry ENABLE ROW LEVEL SECURITY;

-- Autorise l'insertion publique (via clé ANON de l'ESP32)
CREATE POLICY "Autoriser l'insertion des mesures (ESP32)" 
ON public.telemetry 
FOR INSERT 
TO anon, authenticated 
WITH CHECK (true);

-- Autorise la lecture publique (pour le dashboard web)
CREATE POLICY "Autoriser la lecture des mesures (Dashboard)" 
ON public.telemetry 
FOR SELECT 
TO anon, authenticated 
USING (true);

-- 3. Activation de la synchronisation Temps Réel (Supabase Realtime)
ALTER PUBLICATION supabase_realtime ADD TABLE public.telemetry;

-- 4. Index pour accélérer les requêtes d'historique par date
CREATE INDEX IF NOT EXISTS idx_telemetry_created_at ON public.telemetry (created_at DESC);
